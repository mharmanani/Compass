import warnings 
import math
import torch 
from torch import nn


def _no_grad_trunc_normal_(tensor, mean, std, a, b):
    # Cut & paste from PyTorch official master until it's in a few official releases - RW
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1.0 + math.erf(x / math.sqrt(2.0))) / 2.0

    if (mean < a - 2 * std) or (mean > b + 2 * std):
        warnings.warn(
            "mean is more than 2 std from [a, b] in nn.init.trunc_normal_. "
            "The distribution of values may be incorrect.",
            stacklevel=2,
        )

    with torch.no_grad():
        # Values are generated by using a truncated uniform distribution and
        # then using the inverse CDF for the normal distribution.
        # Get upper and lower cdf values
        l = norm_cdf((a - mean) / std)
        u = norm_cdf((b - mean) / std)

        # Uniformly fill tensor with values from [l, u], then translate to
        # [2l-1, 2u-1].
        tensor.uniform_(2 * l - 1, 2 * u - 1)

        # Use inverse cdf transform for normal distribution to get truncated
        # standard normal
        tensor.erfinv_()

        # Transform to proper mean, std
        tensor.mul_(std * math.sqrt(2.0))
        tensor.add_(mean)

        # Clamp to ensure it's in the proper range
        tensor.clamp_(min=a, max=b)
        return tensor


def trunc_normal_(tensor, mean=0.0, std=1.0, a=-2.0, b=2.0):
    # type: (Tensor, float, float, float, float) -> Tensor
    return _no_grad_trunc_normal_(tensor, mean, std, a, b)


def has_batchnorms(model):
    bn_types = (nn.BatchNorm1d, nn.BatchNorm2d, nn.BatchNorm3d, nn.SyncBatchNorm)
    for name, module in model.named_modules():
        if isinstance(module, bn_types):
            return True
    return False


# MIL utilities 
def unstack_variable_length_batch(stacked_tensor, batch_indices):
    num_original_items = batch_indices.unique()
    outputs = [] 

    for idx in num_original_items: 
        outputs.append(stacked_tensor[batch_indices == idx])

    return outputs


def collate_mil_batch(samples): 
    keys = samples[0].keys() 
    outputs = {k: [] for k in keys}
    for sample in samples: 
        for key in keys: 
            outputs[key].append(sample[key])    
    return outputs


def get_batch_indices(tensors):
    lengths = [len(tensor) for tensor in tensors]
    batch_indices = []
    for i in range(len(lengths)):
        batch_indices.extend([i] * lengths[i]) 
    return torch.tensor(batch_indices)
    

def concat_variable_length_batch(tensors): 
    return torch.cat(tensors, dim=0), get_batch_indices(tensors)


def run_model_chunked(module, inputs, max_batch_size=None): 
    if max_batch_size is None or inputs.shape[0] > max_batch_size: 
        return module(inputs)
    else: 
        chunks = inputs.chunk(chunks=inputs.shape[0] // max_batch_size + 1)
        return torch.cat([module(chunk) for chunk in chunks])
